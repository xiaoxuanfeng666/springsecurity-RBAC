-- =============================================================================
-- 增量升级：收敛菜单入口
-- 日期：2026-10-17
-- 目标库：rbac
-- =============================================================================
-- 需求：
--   ① 删除「子系统管理」「子系统菜单管理」「子系统用户授权」三个菜单入口；
--   ② 子系统菜单统一在「菜单管理」页通过「所属系统」切换维护；
--   ③ 子系统管理员给用户授权的入口移到「用户管理」行内。
--
-- 处理方式：
--   - 删除 108（子系统管理）、109（子系统菜单管理）、111（子系统用户授权）
--     以及它们下面的按钮权限点；
--   - 「子系统管理员」的三个权限点（1111/1112/1113）保留，挂到「用户管理」（100）
--     下面，仍然可以在「角色管理 → 分配权限 → 系统权限」里授予；
--   - 清掉这些菜单上的角色授权，避免留下指向已删除菜单的脏关联。
--
-- 执行：
--   mysql -uroot -p --default-character-set=utf8mb4 < sql/upgrade-2026-10-17-remove-subsystem-menus.sql
-- =============================================================================

USE `rbac`;

-- 删除角色对这些菜单/按钮的授权
DELETE FROM `sys_role_menu`
WHERE `menu_id` IN (108, 109, 111, 1081, 1082, 1083, 1084, 1091, 1092, 1093, 1094);

-- 删除菜单与按钮
DELETE FROM `sys_menu`
WHERE `id` IN (108, 109, 111, 1081, 1082, 1083, 1084, 1091, 1092, 1093, 1094);

-- 子系统管理员权限点保留，挂到「用户管理」下（仍可授予）
UPDATE `sys_menu` SET `parent_id` = 100, `sort` = 7 WHERE `id` = 1111;
UPDATE `sys_menu` SET `parent_id` = 100, `sort` = 8 WHERE `id` = 1112;
UPDATE `sys_menu` SET `parent_id` = 100, `sort` = 9 WHERE `id` = 1113;
